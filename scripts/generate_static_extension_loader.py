#!/usr/bin/env python3
# Writes a C source that makes a program link the named statically built extensions. Each extension archive carries a
# root member, duckdb_extension_<name>_root, that registers the extension with the engine; nothing references it, so a
# link that wants the extension has to. Compiling this file into the program does that with no linker flags and no
# per-platform symbol spelling, and a named extension whose archive is missing fails the link.
#
#   LINK_EXTENSIONS="parquet;json" make static_extension_loader     (or: python3 scripts/generate_static_extension_loader.py -o static_extension_loader.c parquet json)
#   cc main.c build/release/static_extension_loader.c libparquet_extension.a libjson_extension.a libduckdb_static.a
import argparse
import os
import re
import sys


def parse_names(values):
    names = []
    for value in values:
        for name in re.split(r'[;\s]+', value):
            if not name:
                continue
            if not re.fullmatch(r'[a-z0-9_]+', name):
                sys.exit(f'invalid extension name: {name!r}')
            if name not in names:
                names.append(name)
    return names


TEMPLATE = os.path.join(
    os.path.dirname(os.path.abspath(__file__)), '..', 'extension', 'loader', 'static_extension_loader.c.in'
)


def generate(names):
    # mirrors duckdb_write_static_extension_loader in extension/extension_build_tools.cmake, which renders the same template
    roots = [f'duckdb_extension_{name}_root' for name in names]
    if not roots:
        return (
            '// Generated by scripts/generate_static_extension_loader.py. Do not edit.\n'
            '// Links no extensions.\n'
            'typedef int duckdb_static_extension_loader_unused;\n'
        )
    values = {
        'LINK_EXTENSION_LIST': ' '.join(names),
        'MSVC_X86_INCLUDES': '\n'.join(f'#pragma comment(linker, "/include:_{root}")' for root in roots),
        'MSVC_INCLUDES': '\n'.join(f'#pragma comment(linker, "/include:{root}")' for root in roots),
        'ROOT_DECLARATIONS': '\n'.join(f'void {root}(void);' for root in roots),
        'ROOT_TABLE': '\n'.join(f'    {root},' for root in roots),
    }
    with open(TEMPLATE) as f:
        content = f.read()
    for key, value in values.items():
        content = content.replace(f'@{key}@', value)
    return content


def main():
    parser = argparse.ArgumentParser(description='Generate a C source that links the named static DuckDB extensions.')
    parser.add_argument('extensions', nargs='*', help='extension names, separated by spaces or semicolons')
    parser.add_argument('--output', '-o', default='-', help='file to write, or - for stdout (default)')
    args = parser.parse_args()
    content = generate(parse_names(args.extensions))
    if args.output == '-':
        sys.stdout.write(content)
    else:
        with open(args.output, 'w') as f:
            f.write(content)


if __name__ == '__main__':
    main()
