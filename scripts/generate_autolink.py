#!/usr/bin/env python3
# Generates the automatic extension linking files from extension/known_extensions.txt:
#  - src/include/duckdb_autolink.h: makes a client translation unit reference duckdb_extension_<name>_root for every
#    known extension
#  - src/main/extension/autolink_fallbacks.cpp: the weak no-op roots for the amalgamation build only. CMake builds
#    generate one object per name from extension/loader/root_fallback.cpp.in instead, so that the engine archive
#    supplies exactly the names whose archive was absent
import os

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
LIST_FILE = os.path.join(ROOT, 'extension', 'known_extensions.txt')
HEADER_FILE = os.path.join(ROOT, 'src', 'include', 'duckdb_autolink.h')
FALLBACK_FILE = os.path.join(ROOT, 'src', 'main', 'extension', 'autolink_fallbacks.cpp')

GENERATED = '// Generated by scripts/generate_autolink.py from extension/known_extensions.txt. Do not edit.\n'


def read_names():
    names = []
    with open(LIST_FILE) as f:
        for line in f:
            line = line.strip()
            if line and not line.startswith('#'):
                names.append(line)
    return names


def write_if_changed(path, content):
    if os.path.exists(path):
        with open(path) as f:
            if f.read() == content:
                return
    with open(path, 'w') as f:
        f.write(content)


def generate_header(names):
    out = GENERATED
    out += '''//
// Automatic extension linking. A translation unit that includes this header references the root member
// of every extension DuckDB knows, so the linker takes each extension archive that is on the link line
// and registers the extension with the engine. libduckdb must come after the extension archives: it
// defines a no-op for every name whose archive is absent, and the linker keeps the first definition it
// meets. duckdb.hpp includes this header; C clients include it next to duckdb.h. Define DUCKDB_NO_AUTOLINK
// to opt out; the engine itself and extensions never take part.
#pragma once

#if !defined(DUCKDB_NO_AUTOLINK) && !defined(DUCKDB_EXTENSION_NAME)
#if defined(_MSC_VER)
// an /include directive is the linker's own way of wanting a symbol nobody references
#if defined(_M_IX86)
'''
    for name in names:
        out += f'#pragma comment(linker, "/include:_duckdb_extension_{name}_root")\n'
    out += '#else\n'
    for name in names:
        out += f'#pragma comment(linker, "/include:duckdb_extension_{name}_root")\n'
    out += '''#endif
#elif defined(__GNUC__) || defined(__clang__)
#ifdef __cplusplus
extern "C" {
#endif
'''
    for name in names:
        out += f'void duckdb_extension_{name}_root(void);\n'
    out += '''#ifdef __cplusplus
}
#endif
// weak, external linkage: every translation unit that includes this header carries one, the linker keeps one
// clang-format off
__attribute__((used, weak)) void (*duckdb_known_extensions[])(void) = {
'''
    for name in names:
        out += f'    duckdb_extension_{name}_root,\n'
    out += '''};
// clang-format on
#endif
#endif
'''
    write_if_changed(HEADER_FILE, out)


def generate_amalgamation_fallbacks(names):
    # The amalgamation is one translation unit, so one file serves; CMake builds instead generate one object
    # per name from extension/loader/root_fallback.cpp.in, and this file compiles to nothing there.
    out = GENERATED
    out += '''// The weak no-op roots for the amalgamation, which has no archive members to keep apart. In a CMake
// build these come from one object per name, generated from extension/loader/root_fallback.cpp.in.
#ifdef DUCKDB_AMALGAMATION
#include "duckdb/common/winapi.hpp"

extern "C" {
'''
    for name in names:
        out += f'DUCKDB_EXTENSION_API __attribute__((weak)) void duckdb_extension_{name}_root(void) {{\n}}\n'
    out += '''}
#endif
'''
    write_if_changed(FALLBACK_FILE, out)


if __name__ == '__main__':
    names = read_names()
    generate_header(names)
    generate_amalgamation_fallbacks(names)
