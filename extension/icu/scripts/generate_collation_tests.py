#!/usr/bin/env python3
"""Writes test/sql/collate/collation_tailorings.test_slow.

The test orders the strings every collation tailors, which is what its rules are about, and
compares a hash of the result. Regenerate it after updating the collation data (see README.md)
and read the diff: a collation whose hash changed is a collation whose ordering changed.

    python3 extension/icu/scripts/generate_collation_tests.py [--duckdb=build/release/duckdb]
"""

import hashlib
import importlib.util
import os
import subprocess
import sys

SCRIPT_DIR = os.path.dirname(os.path.abspath(__file__))
# scripts -> icu -> extension -> the root of the repository
ROOT_DIR = os.path.dirname(os.path.dirname(os.path.dirname(SCRIPT_DIR)))
DEFAULT_DUCKDB = os.path.join(ROOT_DIR, "build", "release", "duckdb")
TEST_PATH = os.path.join(ROOT_DIR, "test", "sql", "collate", "collation_tailorings.test_slow")

#! the tailored strings to order per collation, the longest ones first so that the contractions
#! and the characters the rules are really about are always included
CORPUS_SIZE = 60
#! strings that every corpus holds, so that the tailoring is tested against the root as well
BASELINE = ["a", "A", "z", "Z", "0", "9", " ", "ab", "aa", "ch", "ss", "Müller", "Ångström"]


def tailored_strings():
    """The strings the rules of every collation map, by collation name."""
    spec = importlib.util.spec_from_file_location("gen", os.path.join(SCRIPT_DIR, "generate_collation_data.py"))
    gen = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(gen)

    root = gen.parse_fractional_uca(gen.fetch(gen.CLDR_BASE + "/uca/FractionalUCA.txt", "FractionalUCA.txt"))
    root.compressible[gen.UNASSIGNED_IMPLICIT_LEAD_BYTE] = True
    normalization = gen.parse_unicode_data(gen.fetch(gen.UCD_BASE + "/UnicodeData.txt", "UnicodeData.txt"))
    han = {cp: i for i, cp in enumerate(root.han_order)}

    def implicit_primary(cp):
        return gen.han_primary(han[cp]) if cp in han else gen.unassigned_primary(cp)

    tailorings, sources = gen.build_tailorings(root, normalization, implicit_primary)
    result = {}
    for name, source in sorted(sources.items()):
        # the script variants of a locale are not registered as collations
        parts = name.split("_")
        if len(parts) > 1 and len(parts[1]) == 4:
            continue
        result[name] = ["".join(chr(cp) for cp in key) for key in tailorings[source].mappings]
    return result


def sql_values(strings):
    return ", ".join("('" + s.replace("'", "''") + "')" for s in strings)


def hash_of(duckdb, collation, strings):
    """The result hash the test framework computes for the ordered strings."""
    query = "select s from (values %s) t(s) order by s collate \"%s\", s;" % (sql_values(strings), collation)
    out = subprocess.run([duckdb, "-noheader", "-list", "-c", query], capture_output=True, text=True)
    if out.returncode != 0:
        raise SystemExit("%s: %s" % (collation, out.stderr.strip()))
    values = out.stdout.split("\n")[:-1] if out.stdout.endswith("\n") else out.stdout.split("\n")
    digest = hashlib.md5()
    for value in values:
        digest.update(value.encode("utf-8"))
        digest.update(b"\n")
    return len(values), digest.hexdigest()


def main():
    duckdb = DEFAULT_DUCKDB
    for arg in sys.argv[1:]:
        if arg.startswith("--duckdb="):
            duckdb = arg[len("--duckdb=") :]

    corpora = tailored_strings()
    sys.stderr.write("writing the ordering of %d collations\n" % len(corpora))

    out = [
        "# name: test/sql/collate/collation_tailorings.test_slow",
        "# description: Test the ordering of the strings every collation tailors",
        "# group: [collate]",
        "",
        "# This file is generated by extension/icu/scripts/generate_collation_tests.py",
        "",
        "require icu",
        "",
    ]
    for name in sorted(corpora):
        # the longest strings first, they are the contractions the rules add
        strings = sorted(set(corpora[name]), key=lambda s: (-len(s), s))[:CORPUS_SIZE]
        strings = sorted(set(strings) | set(BASELINE))
        count, digest = hash_of(duckdb, name, strings)
        out.append("# %s" % name)
        out.append("query I")
        out.append("SELECT s FROM (VALUES %s) t(s) ORDER BY s COLLATE \"%s\", s" % (sql_values(strings), name))
        out.append("----")
        out.append("%d values hashing to %s" % (count, digest))
        out.append("")
    with open(TEST_PATH, "w") as f:
        f.write("\n".join(out))
    sys.stderr.write("wrote %s\n" % TEST_PATH)


if __name__ == "__main__":
    main()
