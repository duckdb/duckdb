#!/usr/bin/env python3
"""Removes items from the inlined ICU data package.

makedata.sh builds the data package from the filters in filters.json, which needs a full
ICU build. This script applies a filter to the package that is already inlined in
stubdata.cpp, so that data that is no longer used can be dropped without rebuilding ICU.
It writes the new stubdata.cpp to stdout.

    python3 extension/icu/scripts/strip-data.py coll/
"""

import re
import struct
import sys

STUBDATA = "extension/icu/third_party/icu/stubdata/stubdata.cpp"
#! the items of a data package start at an offset that is a multiple of this
ITEM_ALIGNMENT = 16


def read_package(path):
    """Reads the byte array of the inlined data package."""
    text = open(path).read()
    start = text.index("{", text.index("U_ICUDATA_ENTRY_POINT"))
    end = text.index("};", start)
    return bytes(int(value) for value in text[start + 1 : end].replace("\n", "").split(",") if value.strip())


def split_package(data):
    """Splits a data package into its header and its items."""
    table = struct.unpack_from("<H", data, 0)[0]
    count = struct.unpack_from("<I", data, table)[0]
    offsets = [struct.unpack_from("<II", data, table + 4 + index * 8) for index in range(count)]
    items = []
    for index, (name_offset, data_offset) in enumerate(offsets):
        name_start = table + name_offset
        name = data[name_start : data.index(b"\0", name_start)].decode()
        limit = offsets[index + 1][1] if index + 1 < count else len(data) - table
        items.append((name, data[table + data_offset : table + limit]))
    return data[:table], items


def build_package(header, items):
    """Builds a data package from its header and its items."""
    names = b"".join(name.encode() + b"\0" for name, _ in items)
    table_size = 4 + len(items) * 8 + len(names)
    data_start = (table_size + ITEM_ALIGNMENT - 1) // ITEM_ALIGNMENT * ITEM_ALIGNMENT

    table = struct.pack("<I", len(items))
    name_offset = 4 + len(items) * 8
    data_offset = data_start
    for name, item in items:
        table += struct.pack("<II", name_offset, data_offset)
        name_offset += len(name) + 1
        data_offset += len(item)
    return header + table + names + b"\0" * (data_start - table_size) + b"".join(item for _, item in items)


def main():
    if len(sys.argv) < 2:
        raise SystemExit("usage: strip-data.py <prefix to remove> ...")
    prefixes = sys.argv[1:]
    header, items = split_package(read_package(STUBDATA))

    def keep(name):
        # the name of an item starts with the name of the package
        path = name.split("/", 1)[1] if "/" in name else name
        return not any(path.startswith(prefix) for prefix in prefixes)

    kept = [(name, item) for name, item in items if keep(name)]
    removed = len(items) - len(kept)
    package = build_package(header, kept)
    sys.stderr.write(
        "removed %d of %d items, %d bytes left of %d\n"
        % (removed, len(items), len(package), sum(len(item) for _, item in items))
    )

    sys.stdout.write(
        """
// This file is generated by scripts/inline-data.py, do not edit it manually //

#include "unicode/utypes.h"
#include "unicode/udata.h"
#include "unicode/uversion.h"

extern "C" U_EXPORT const unsigned char U_ICUDATA_ENTRY_POINT [] = {
\t%s
};
"""
        % ",".join(str(byte) for byte in package)
    )


if __name__ == "__main__":
    main()
